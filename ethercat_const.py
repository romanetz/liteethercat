#!/usr/bin/env python3
"""Константы EtherCAT ESC."""

EC_CMD_NOP  = 0x00
EC_CMD_APRD = 0x01
EC_CMD_APWR = 0x02
EC_CMD_APRW = 0x03
EC_CMD_FPRD = 0x04
EC_CMD_FPWR = 0x05
EC_CMD_FPRW = 0x06
EC_CMD_BRD  = 0x07
EC_CMD_BWR  = 0x08
EC_CMD_BRW  = 0x09
EC_CMD_LRD  = 0x0A
EC_CMD_LWR  = 0x0B
EC_CMD_LRW  = 0x0C

ETHERTYPE_ECAT = 0x88A4

# Карта памяти ESC
ESC_REGS_START   = 0x0000
ESC_DPRAM_START  = 0x1000
ESC_DPRAM_END    = 0x1FFF
ESC_MEM_END      = 0x3FFF   # 16KB: регистры + DPRAM + 2 shadow-буфера

EC_FMMU_START = 0x0600
EC_FMMU_SIZE  = 0x0010
EC_FMMU_COUNT = 8

EC_SM_START   = 0x0800
EC_SM_SIZE    = 0x0008
EC_SM_COUNT   = 4

BRAM_READ_LATENCY = 4
